        logger.info(f"   Music: {music_query}")
        logger.info(f"   LED: {lighting_config['color']} {lighting_config['effect']} @ {lighting_config['brightness']}")
        
        return {
            'music_query': music_query,
            'lighting': lighting_config,
            'confidence': confidence,
        }
    
